#!/usr/bin/env python3
"""Generate Sources/Resources/<lang>.lproj/Localizable.strings from Sources/Resources/Localization.tsv.

Keys are the Simplified Chinese strings passed to L(...) in Sources. The script fails
when a key has no row, a row is unused, or format specifiers differ between languages.
Run it after adding or changing interface text."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
indirect = ["全局", "应用", "框选", "截图窗口"]  # ShortcutAction.group values, shown through L(group)
pattern = re.compile(r'\bL\("((?:[^"\\\n]|\\.)*)"')
summary = re.compile(r'summaryKey: "((?:[^"\\\n]|\\.)*)"')
keys = []
for path in sorted((root / "Sources").rglob("*.swift")):
    text = path.read_text()
    for match in [*pattern.finditer(text), *summary.finditer(text)]:
        if match.group(1) not in keys: keys.append(match.group(1))
keys += [k for k in indirect if k not in keys]

lines = (root / "Sources/Resources/Localization.tsv").read_text(encoding="utf-8").split("\n")
languages = lines[0].split("\t")
rows, errors = {}, []
for number, line in enumerate(lines[1:], start=2):
    if not line: continue
    columns = line.split("\t")
    if len(columns) != len(languages): errors.append(f"line {number}: {len(columns)} columns"); continue
    rows[columns[0]] = columns
spec = re.compile(r'%(?:\d\$)?(@|ld)')
errors += [f"missing translation: {k}" for k in keys if k not in rows]
errors += [f"unused row: {k}" for k in rows if k not in keys]
for key, columns in rows.items():
    for language, value in zip(languages, columns):
        if sorted(spec.findall(value)) != sorted(spec.findall(key)): errors.append(f"{language} format mismatch: {key}")
if errors: sys.exit("\n".join(errors))

def escape(s): return s.replace("\\n", "\n").replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
for index, language in enumerate(languages):
    folder = root / f"Sources/Resources/{language}.lproj"
    folder.mkdir(parents=True, exist_ok=True)
    body = [f'"{escape(k)}" = "{escape(rows[k][index])}";' for k in keys]
    (folder / "Localizable.strings").write_text("/* Generated by scripts/localize.py from Sources/Resources/Localization.tsv. */\n" + "\n".join(body) + "\n", encoding="utf-8")
print(f"{len(keys)} strings × {len(languages)} languages")
